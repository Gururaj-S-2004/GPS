def dist(a, b):
    dlat = (b[1]-a[1])*111000
    dlon = (b[0]-a[0])*108100*math.cos(math.radians((a[1]+b[1])/2))
    return math.sqrt(dlat**2+dlon**2)

def subsample(coords, min_dist_m=20):
    """Keep only points that are at least min_dist_m apart."""
    out = [coords[0]]
    for p in coords[1:]:
        if dist(out[-1], p) >= min_dist_m:
            out.append(p)
    return out

